DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT p.oid::regprocedure AS sig
      FROM pg_proc p
      JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public'
       AND p.prokind = 'f'
       AND p.proname <> 'calendar_feed'
  LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon', r.sig);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO authenticated, service_role', r.sig);
  END LOOP;
END $$;

REVOKE EXECUTE ON FUNCTION public.digest_daily() FROM authenticated;
REVOKE EXECUTE ON FUNCTION public.digest_weekly_self() FROM authenticated;
REVOKE EXECUTE ON FUNCTION public.digest_weekly_manager() FROM authenticated;